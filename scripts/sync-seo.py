#!/usr/bin/env python3
"""Keep sitemap lastmod, llms.txt coverage, and canonical redirects in sync.

Plain static site: this is safe to run locally or as the Netlify build command.
It does not rewrite blog prose. It updates post <lastmod> from each post's
dateModified, refuses to deploy if llms.txt is missing a canonical URL, and
rewrites _redirects for the extensionless -> .html canonical.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BLOG = ROOT / "blog"
SITEMAP = ROOT / "sitemap.xml"
LLMS = ROOT / "llms.txt"
REDIRECTS = ROOT / "_redirects"
OG_DIR = ROOT / "assets" / "og"
SITE = "https://aliahmedawan.me"

TRAINING_URL = f"{SITE}/ai-training.html"
TRAINING_LASTMOD = "2026-10-26"


def posts():
    found = []
    for path in sorted(BLOG.glob("*.html")):
        if path.name == "index.html":
            continue
        html = path.read_text()
        canonical = re.search(r'<link rel="canonical" href="([^"]+)"', html)
        modified = re.search(r'"dateModified": "(\d{4}-\d{2}-\d{2})"', html)
        if not canonical or not modified:
            sys.exit(f"{path.name} is missing a canonical URL or dateModified")
        slug = path.stem
        expected = f"{SITE}/blog/{slug}.html"
        if canonical.group(1) != expected:
            sys.exit(f"{path.name} canonical is {canonical.group(1)}, expected {expected}")
        image = re.search(r'<meta property="og:image" content="([^"]+)"', html)
        expected_image = f"{SITE}/assets/og/{slug}.png"
        if not image or image.group(1) != expected_image:
            sys.exit(f"{path.name} og:image should be {expected_image}")
        if not (OG_DIR / f"{slug}.png").is_file():
            sys.exit(f"missing {OG_DIR / (slug + '.png')}")
        found.append((slug, canonical.group(1), modified.group(1)))
    if not found:
        sys.exit("no blog posts found")
    return found


def update_sitemap(rows):
    xml = SITEMAP.read_text()
    by_loc = {url: lastmod for _slug, url, lastmod in rows}

    def repl(match):
        block = match.group(0)
        loc = re.search(r"<loc>([^<]+)</loc>", block).group(1)
        if loc not in by_loc:
            return block
        return re.sub(
            r"<lastmod>[^<]+</lastmod>",
            f"<lastmod>{by_loc[loc]}</lastmod>",
            block,
            count=1,
        )

    xml2 = re.sub(r"<url>.*?</url>", repl, xml, flags=re.S)
    if f"<loc>{TRAINING_URL}</loc>" not in xml2:
        entry = f"""  <url>
    <loc>{TRAINING_URL}</loc>
    <lastmod>{TRAINING_LASTMOD}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>
"""
        xml2 = xml2.replace("</urlset>", entry + "</urlset>")
    if xml2 != xml:
        SITEMAP.write_text(xml2)
        print("updated sitemap.xml")
    else:
        print("sitemap.xml already in sync")


def check_llms(rows):
    text = LLMS.read_text()
    missing = [url for _slug, url, _date in rows if url not in text]
    if TRAINING_URL not in text:
        missing.append(TRAINING_URL)
    if missing:
        print("llms.txt is missing:", file=sys.stderr)
        for url in missing:
            print(" ", url, file=sys.stderr)
        sys.exit(1)
    print("llms.txt covers every canonical URL")


def write_redirects(rows):
    lines = [
        "# Generated by scripts/sync-seo.py. Do not edit by hand.",
        "# Canonical blog posts are the .html URLs. Extensionless paths 301 there.",
        "# Forced because Netlify also serves /blog/slug from blog/slug.html.",
        "# /blog -> /blog/ is an edge function: a redirect rule cannot add a slash.",
        "",
    ]
    for slug, url, _date in rows:
        path = url.removeprefix(SITE)
        lines.append(f"/blog/{slug}  {path}  301!")
    lines.append("/blog/index.html  /blog/  301!")
    lines.append("/ai-training  /ai-training.html  301!")
    lines.append("")
    text = "\n".join(lines)
    if not REDIRECTS.exists() or REDIRECTS.read_text() != text:
        REDIRECTS.write_text(text)
        print("updated _redirects")
    else:
        print("_redirects already in sync")


def main():
    rows = posts()
    if not (OG_DIR / "ai-training.png").is_file():
        sys.exit("missing assets/og/ai-training.png")
    update_sitemap(rows)
    check_llms(rows)
    write_redirects(rows)
    print(f"{len(rows)} posts")


if __name__ == "__main__":
    main()
